    [Fact]
    public void ControllerRoutesMatchApprovedApiSurface()
    {
        var actual = typeof(AuthController).Assembly.GetTypes()
            .Where(type => !type.IsAbstract && typeof(ControllerBase).IsAssignableFrom(type))
            .SelectMany(type =>
            {
                var prefix = type.GetCustomAttributes(typeof(RouteAttribute), true)
                    .Cast<RouteAttribute>().SingleOrDefault()?.Template ?? "";
                return type.GetMethods().Where(method => method.DeclaringType == type)
                    .SelectMany(method => method.GetCustomAttributes(typeof(HttpMethodAttribute), true)
                        .Cast<HttpMethodAttribute>()
                        .SelectMany(attribute => attribute.HttpMethods.Select(httpMethod =>
                            $"{httpMethod} {Combine(prefix, attribute.Template)}")));
            })
            .ToHashSet(StringComparer.Ordinal);

        Assert.Equal(ExpectedRoutes.Order(), actual.Order());
    }

    private static string Combine(string prefix, string? template)
    {
        if (!string.IsNullOrEmpty(template) && template.StartsWith('/'))
            return template;

        var route = string.Join('/', new[] { prefix, template }
            .Where(part => !string.IsNullOrWhiteSpace(part))
            .Select(part => part!.Trim('/')));
        return route.Length == 0 ? "/" : "/" + route;
    }
